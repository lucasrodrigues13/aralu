module.exports = async (p, H) => {
  const D = 'mat-dialog-container';
  await H.go(p, '/orcamentos-funil');
  await H.click(p, 'Parcelas', 'main');
  await H.wd(p);
  await H.fill(p, 'Número de parcelas', '5', D);
  await H.fill(p, 'Vencimento da 1ª parcela', '10/01/2027', D);
  await H.click(p, 'Tem entrada', D);
  await H.wait(p, 500);
  await H.fill(p, 'Valor da entrada', '540000', D);
  await H.fill(p, 'Data da entrada', '10/12/2026', D);
  await H.dlg(p, '22a-parcelas-form');
  await H.click(p, 'Gerar parcelas', D);
  await H.wait(p, 1500);
  await H.dlg(p, '22b-parcelas-geradas');
  await H.dump(p);
  await H.esc(p);
  const link = require('fs').readFileSync('link-proposta.txt', 'utf8').replace('http://localhost:8080', '');
  const ctx = await p.browser().createBrowserContext();
  const a = await ctx.newPage();
  await a.setViewport({ width: 1366, height: 850 });
  await a.emulateMediaFeatures([{ name: 'prefers-color-scheme', value: 'light' }]);
  await H.go(a, link);
  await H.shot(a, '24a-proposta-publica', true);
  await H.dump(a, 'body');
  await H.click(a, 'Aceitar');
  await H.wait(a, 1000);
  await H.shot(a, '24b-proposta-aceitar', true);
  await H.dump(a, 'body');
  await ctx.close();
};
